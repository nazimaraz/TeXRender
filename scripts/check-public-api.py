#!/usr/bin/env python3
"""Check that public headers and install metadata changed intentionally."""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "docs/public-api-snapshot.txt"


def public_paths() -> list[Path]:
    paths = sorted((ROOT / "include/texgui").glob("*.hpp"))
    paths.extend(
        [
            ROOT / "cmake/texguiConfig.cmake.in",
            ROOT / "cmake/texguiHelpers.cmake",
            ROOT / "cmake/texgui.pc.in",
        ]
    )
    return sorted(paths, key=lambda path: path.relative_to(ROOT).as_posix())


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot_text() -> str:
    lines = [
        "# Public API Snapshot",
        "",
        "# Generated by scripts/check-public-api.py --update.",
        "# Review public API, CMake export, and pkg-config changes before updating.",
        "",
    ]
    for path in public_paths():
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"{digest(path)}  {rel}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update", action="store_true", help="rewrite docs/public-api-snapshot.txt")
    args = parser.parse_args()

    expected = snapshot_text()
    if args.update:
        SNAPSHOT.write_text(expected, encoding="utf-8")
        print(f"updated {SNAPSHOT.relative_to(ROOT)}")
        return 0

    if not SNAPSHOT.exists():
        print(f"missing {SNAPSHOT.relative_to(ROOT)}; run scripts/check-public-api.py --update", file=sys.stderr)
        return 1

    actual = SNAPSHOT.read_text(encoding="utf-8")
    if actual != expected:
        print("public API snapshot is out of date", file=sys.stderr)
        print("Review the public surface, update docs/changelog if needed, then run:", file=sys.stderr)
        print("  scripts/check-public-api.py --update", file=sys.stderr)
        return 1

    print(f"public API snapshot checked ({len(public_paths())} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
